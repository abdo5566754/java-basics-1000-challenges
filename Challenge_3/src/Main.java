
// 3. Calculate the average of three numbers.
public class Main {
    public static void main(String[] args) {

        // declare four double variables;
        double n1, n2, n3, avg;

        // initial value to n1 variable
        n1 = 188;


        // initial value to n1 variable
        n2 = 135;


        // initial value to n1 variable
        n3 = 88;

        // calc average to n1, n2, n3 and assignment to avg
        avg = (n1 + n2 + n3) / 3;


        // print the result
        System.out.println("Result is : " + avg);

    }
}