
// Calculate the area of a rectangle from its length and width.

public class Main {
    public static void main(String[] args) {

        // Declare double variable for width
        double width = 10.3;

        // Declare double variable for length
        double length = 15;

        // Declare double variable for area
        double area = width * length;

        // print the result for user
        System.out.println("Area of rectangle is : " + area);
    }
}
